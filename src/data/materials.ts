// Helper functions
export function getMaterialById(id: string): Material | undefined {
  return materials.find((m) => m.id === id);
}

export function getMaterialImageUrl(materialId: string): string {
  return `/materials/${materialId}.webp`;
}

export function getMaterialsByCategory(category: MaterialCategory): Material[] {
  return materials.filter((m) => m.category === category);
}

export function getMaterialByBaseName(baseName: string): Material[] {
  return materials.filter((m) => m.baseName === baseName);
}

export function getMaterialByNameAndQuality(
  baseName: string,
  quality: MaterialQualityTier
): Material | undefined {
  return materials.find(
    (m) => m.baseName === baseName && m.quality === quality
  );
}

// Get all unique base materials (without qualities)
export function getUniqueMaterials(): {
  baseName: string;
  category: MaterialCategory;
}[] {
  const unique = new Map<string, MaterialCategory>();
  materials.forEach((m) => {
    if (!unique.has(m.baseName)) {
      unique.set(m.baseName, m.category);
    }
  });
  return Array.from(unique.entries()).map(([baseName, category]) => ({
    baseName,
    category,
  }));
}
